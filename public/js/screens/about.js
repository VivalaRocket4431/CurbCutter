import { h, icon } from '../ui/dom.js';
import { pageHead, externalLink } from '../ui/components.js';
import { SOURCES, CONTENT_CHECKED } from '../data/sources.js';
import { longDate } from '../lib/dates.js';
import { APP } from '../config.js';

export async function renderAbout() {
  const sources = Object.values(SOURCES);
  const node = h('div', { class: 'screen about' },
    pageHead({ title: 'About CurbCutter', lede: 'A free tool that helps people with disabilities get accessibility barriers fixed at Texas businesses.' }),
    h('section', { class: 'block prose' },
      h('h2', null, 'Why it exists'),
      h('p', null, 'In most cases, the only way a business learns that its parking or entrance shuts people out is when someone tells it. CurbCutter makes that request specific and well sourced, and gives it a clear path to agencies that can require a fix when asking isn\'t enough.'),
      h('p', null, 'The name comes from the curb cut: the small ramp in a sidewalk curb that disability activists fought for, which ended up helping everyone pushing a stroller, pulling a suitcase, or rolling a delivery cart. A curb cutter is the machine that does the cutting.'),
      h('p', null, 'Disability advocates in Texas have said there is no mechanism that makes a business fix accessibility, short of asking. CurbCutter is built to be that mechanism.'),
    ),
    h('section', { class: 'block prose' },
      h('h2', null, 'Your privacy'),
      h('ul', { class: 'prose-list' },
        h('li', null, 'No accounts, no ads, no tracking.'),
        h('li', null, 'Your reports and photos are saved only on this device.'),
        h('li', null, 'Nothing leaves your phone unless you email, share, print, or back it up.'),
        h('li', null, 'Photos are shrunk and their hidden location data is removed.'),
      ),
      h('p', { class: 'links-row', 'data-needs-app': '' },
        h('a', { href: 'privacy/' }, 'Read the full privacy policy'),
        h('a', { href: 'support/' }, 'Support'),
      ),
    ),
    h('section', { class: 'block prose' },
      h('h2', null, 'How the information is checked'),
      h('p', null, `Every rule, number, and phone line comes from an official or primary source, listed below. A person last checked them on ${longDate(CONTENT_CHECKED)}. Letters are built from fixed templates, not generated by AI, so the same facts always produce the same text.`),
      h('p', null, 'Every letter is a draft. You can change any word, and nothing is sent unless you send it.'),
      h('p', null, 'Each problem is labeled by how firm the rule is ("Required," "Required when built or remodeled," "Must be kept working," "A fair request," or "The city\'s job") so letters never claim more than the law does.'),
      h('p', null, h('strong', null, 'This is general information, not legal advice.'), ' For legal advice, contact Disability Rights Texas or a lawyer.'),
      h('details', { class: 'sources', open: true },
        h('summary', null, icon('scale', { size: 18 }), `All sources (${sources.length})`),
        h('ul', null, sources.map((s) => h('li', null, externalLink(s.url, s.title), h('span', { class: 'source-meta' }, `${s.publisher}. ${s.kind}. Checked ${longDate(s.checked)}.`)))),
      ),
    ),
    h('section', { class: 'block prose' },
      h('h2', null, 'Credits'),
      h('p', null, 'Text is set in Atkinson Hyperlegible Next, designed by the Braille Institute for readers with low vision, and Overpass, inspired by U.S. highway signs. Both are free under the SIL Open Font License.'),
      APP.feedbackEmail ? h('p', null, 'Questions, corrections, or a success story? ', h('a', { href: `mailto:${APP.feedbackEmail}` }, APP.feedbackEmail)) : null,
    ),
  );
  return { title: 'About', node };
}
